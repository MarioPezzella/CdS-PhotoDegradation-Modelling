% =========================================================================
% This script performs monotonic smoothing of the y-averaged CdS relative
% concentration profiles obtained from the preprocessed synchrotron data.
% The smoothing procedure is based on a functional characterization of the
% space of positive, smooth, and monotonic functions. It exploits a
% regularized combination of Legendre polynomials coupled with a II-order
% ordinary differential equation.
%
% The script first checks whether the preprocessed data are available in
% PreProcessed_Data.mat. If the file is not found, the data processing
% script GH_Data_Processing.m is executed and its generated figures are
% closed immediately.
%
% The smoothed data are saved in Smoothed_Data.mat. If this file already
% exists, the previously computed smoothing results are loaded directly.
%
% The script also generates figures comparing the cropped data with the
% smoothed profiles and figures comparing the smoothing error with the
% standard deviation of the experimental data.
% =========================================================================

%% Data loading
clc; close all
global regolarizer
dataPath = fileparts(mfilename('fullpath'));
dataFile = fullfile(dataPath,'PreProcessed_Data.mat');
smoothedFile = fullfile(dataPath,'Smoothed_Data.mat');

% =========================================================================
% Load preprocessed data
% =========================================================================
if isfile(dataFile)
    fprintf('Loading previously elaborated data.\n');
    load(dataFile);
else
    fprintf('PreProcessed data not found. Running GH_Data_Processing.m.\n');
    run(fullfile(dataPath,'GH_Data_Processing.m'));
    % Close figures generated by the data processing script
    close all
    dataPath = fileparts(mfilename('fullpath'));
    dataFile = fullfile(dataPath,'PreProcessed_Data.mat');
    smoothedFile = fullfile(dataPath,'Smoothed_Data.mat');
end

