% =========================================================================
% Local functions
% =========================================================================
function [W,coeffs] = legendre_fitting(y_data,t_data,N)
    global regolarizer
    n = length(t_data);
    a = t_data(1);
    b = t_data(end);
    t_shift = 2*(t_data-a)/(b-a)-1;
    P = zeros(n,N);
    for k = 1:N
        P(:,k) = legendreP(k-1,t_shift);
    end
    W = @(c,t) P*c;
    regolar = (b-a)./(1+2*(0:1:N-1));
    errorFunc = @(c) norm(y_data-solve_ode(t_data,W(c,t_data),y_data),2)^2 ...
                     + regolarizer.*(regolar*c.^2);
    initial_guess = zeros(N,1);
    options = optimoptions('fmincon','Algorithm','interior-point', ...
        'Display','off','MaxFunctionEvaluations',9e3, ...
        'OptimalityTolerance',1e-14,'StepTolerance',1e-14, ...
        'UseParallel',true);
    coeffs = fmincon(errorFunc,initial_guess,[],[],[],[],[],[],[],options);
end

function f_vals = solve_ode(t_data,w_values,y_data)
    % The II order ODE f''(t) = w(t) f'(t) is numerically solved with ode45
    f0 = min(y_data);
    f0_prime = abs((y_data(1)-y_data(2))/(t_data(1)-t_data(2)));
    w_interp = @(t) interp1(t_data,w_values,t,'spline','extrap');
    odeFunc = @(t,f) [f(2); w_interp(t)*f(2)];
    [~,f_sol] = ode45(odeFunc,t_data,[f0; f0_prime]);
    f_vals = f_sol(:,1);
end

function f_vals = solve_ode_dense(t_data,x_dense,w_values,y_data)
    f0 = min(y_data);
    f0_prime = abs((y_data(1)-y_data(2))/(t_data(1)-t_data(2)));
    w_interp = @(t) interp1(t_data,w_values,t,'spline','extrap');
    odeFunc = @(t,f) [f(2); w_interp(t)*f(2)];
    [~,f_sol] = ode45(odeFunc,x_dense,[f0; f0_prime]);
    f_vals = f_sol(:,1);
end