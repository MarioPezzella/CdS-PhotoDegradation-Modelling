    % =====================================================================
    % Sample t7 (D1) 
    % =====================================================================
    fprintf('Smoothing Sample t7. \n');
    regolarizer = 0.1e-4;
    t_data = x_crop_adim;
    y_data = Adim_D1_mean;
    y_data(2) = abs(y_data(5)/y_data(6))*y_data(1);
    N_polynomials = 30;
    [W_D1,coeffs_D1] = legendre_fitting(y_data,t_data,N_polynomials);
    fitted_value_D1 = solve_ode(t_data,W_D1(coeffs_D1,t_data),y_data);
    fitted_value_dense_D1 = solve_ode_dense(t_data,x_dense, ...
        W_D1(coeffs_D1,t_data),y_data);
    fitted_value_dense_D1 = min(1,fitted_value_dense_D1);

    % =====================================================================
    % Sample t9 (B2) 
    % =====================================================================
    fprintf('Smoothing Sample t9. \n');
    regolarizer = 0.05e-4;
    t_data = x_crop_adim;
    y_data = Adim_B2_mean;
    y_data(1) = 0.85;
    y_data(2) = 0.855;
    N_polynomials = 25;
    [W_B2,coeffs_B2] = legendre_fitting(y_data,t_data,N_polynomials);
    fitted_value_B2 = solve_ode(t_data,W_B2(coeffs_B2,t_data),y_data);
    fitted_value_dense_B2 = solve_ode_dense(t_data,x_dense, ...
        W_B2(coeffs_B2,t_data),y_data);
    fitted_value_dense_B2 = min(1,fitted_value_dense_B2);

    % =====================================================================
    % Sample t10 (B1) 
    % =====================================================================
    fprintf('Smoothing Sample t10. \n');
    regolarizer = 3e-4;
    t_data = x_crop_adim;
    y_data = Adim_B1_mean;
    N_polynomials = 25;
    [W_B1,coeffs_B1] = legendre_fitting(y_data,t_data,N_polynomials);
    fitted_value_B1 = solve_ode(t_data,W_B1(coeffs_B1,t_data),y_data);
    fitted_value_dense_B1 = solve_ode_dense(t_data,x_dense, ...
        W_B1(coeffs_B1,t_data),y_data);
    fitted_value_dense_B1 = min(1,fitted_value_dense_B1);

    fprintf('Smoothing procedure completed.\n');
    fprintf('\n');

    % =====================================================================
    % Smoothing errors
    % =====================================================================
    sigma_C1_std_LAST = std(CdSC1_crop(1:N_Raw_crop_all,:),0,2);
    sigma_C2_std_LAST = std(CdSC2_crop(1:N_Raw_crop_all,:),0,2);
    sigma_D1_std_LAST = std(CdSD1_crop(1:N_Raw_crop_all,:),0,2);
    sigma_B1_std_LAST = std(CdSB1_crop(1:N_Raw_crop_all,:),0,2);
    sigma_B2_std_LAST = std(CdSB2_crop(1:N_Raw_crop_all,:),0,2);
    err_C2 = abs(fitted_value_C2-Adim_C2_mean);
    err_C1 = abs(fitted_value_C1-Adim_C1_mean);
    err_D1 = abs(fitted_value_D1-Adim_D1_mean);
    err_B1 = abs(fitted_value_B1-Adim_B1_mean);
    err_B2 = abs(fitted_value_B2-Adim_B2_mean);

