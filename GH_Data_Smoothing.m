       size(CdSC2_crop,1) size(CdSB2_crop,1)];
N_Raw_crop_all = min(Szs);

Adim_C1_mean = CdSC1_crop_mean(1:N_Raw_crop_all);
Adim_D1_mean = CdSD1_crop_mean(1:N_Raw_crop_all);
Adim_B1_mean = CdSB1_crop_mean(1:N_Raw_crop_all);
Adim_B2_mean = CdSB2_crop_mean(1:N_Raw_crop_all);
