else
    fprintf('Smoothed data not found. Starting smoothing procedure.\n');
    fprintf('\n');

    % =====================================================================
    % Sample t1 (C2) 
    % =====================================================================
    fprintf('Smoothing Sample t1. \n');
    regolarizer = 0.5e-4;
    t_data = x_crop_adim;
    y_data = Adim_C2_mean;
    N_polynomials = 25;
    [W_C2,coeffs_C2] = legendre_fitting(y_data,t_data,N_polynomials);
